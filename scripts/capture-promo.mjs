import {chromium} from 'playwright';
import {mkdir} from 'node:fs/promises';
import {resolve} from 'node:path';

const output=resolve(process.argv[2]||'../repelon-promo/assets');
await mkdir(output,{recursive:true});
const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:440,height:900},deviceScaleFactor:2,locale:'es-CO'});
await page.goto(process.env.APP_URL||'http://127.0.0.1:5173/');
await page.getByRole('heading',{name:'¿Qué necesitas hacer?',exact:true}).waitFor();
await page.evaluate(()=>document.fonts.ready);
const dialog=()=>page.locator('dialog[open]').last();
const save=async(name,selector)=>{
  await page.mouse.move(0,0);
  await page.evaluate(()=>document.activeElement?.blur());
  await selector.screenshot({path:resolve(output,name),animations:'disabled'});
};
await save('inicio.png',page.locator('.home-actions'));
await page.getByRole('button',{name:'Anotar un dato',exact:false}).click();
await save('opciones.png',dialog());
await save('opcion-peso.png',dialog().locator('.record-choice').first());
await page.getByRole('button',{name:'Anotar peso de ganado',exact:false}).click();
await page.getByLabel('Animal',{exact:true}).selectOption('a1');
await page.locator('input[name="date"]').fill('2026-10-02');
await save('animal.png',dialog());
await save('animal-form.png',dialog().locator('.record-form'));
await dialog().getByRole('button',{name:'Continuar',exact:true}).click();
await page.getByLabel('Peso en kilogramos',{exact:true}).fill('402');
await page.getByLabel('Método',{exact:true}).selectOption('Báscula');
await save('peso.png',dialog());
await save('peso-form.png',dialog().locator('.record-form'));
await dialog().getByRole('button',{name:'Continuar',exact:true}).click();
await save('revision.png',dialog());
await save('revision-form.png',dialog().locator('.record-form'));
await dialog().getByRole('button',{name:'Guardar pesaje',exact:true}).click();
await dialog().getByRole('heading',{name:'Pesaje guardado',exact:true}).waitFor();
await save('guardado.png',dialog());
await dialog().getByRole('button',{name:'Volver al inicio',exact:true}).click();
await page.getByRole('button',{name:'Ayuda',exact:true}).click();
await save('ayuda.png',dialog());
await save('letras.png',dialog().locator('.help-text-size'));
await browser.close();
console.log(`7 pantallas reales de ejemplo guardadas en ${output}`);
