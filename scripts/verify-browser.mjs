async function reviewForm(p,values){
 for(let step=0;step<5;step++){
  if(await dialog(p).getByRole('heading',{name:'Revisa tu anotación',exact:true}).count())return;
  for(const [name,value] of Object.entries(values)){
   const field=dialog(p).locator(`[name="${name}"]`);
   if(await field.count()&&await field.isVisible()){
    if(await field.evaluate(e=>e.tagName==='SELECT'))await field.selectOption(String(value));else await field.fill(String(value));
   }
  }
  await dialog(p).getByRole('button',{name:'Continuar',exact:true}).click();
  if(await dialog(p).locator('.form-error').count())throw new Error(await dialog(p).locator('.form-error').innerText());
 }
 throw new Error('The form never reached its review step');
}
